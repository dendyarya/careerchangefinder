"""Check data/seo/short-names.json against O*NET 31.0. Exits 1 on any problem; writes docs/short-names.md.

Each short name must be either
  (T) a shortening of the official title: its words appear in the official title in the same order, or
  (O) an O*NET alternate title (Job Titles) or reported title for that occupation, made plural
      (the part before any "(...)" expansion counts, e.g. "CNC Operator (Computer ...)").
It must be 46 characters or less and unique among all career names and short names.
"""
import json
import pathlib
import re
import sys

import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[2]
ONET = ROOT / "data" / "raw" / "onet" / "db_31_0_excel"
names = json.loads((ROOT / "data" / "seo" / "short-names.json").read_text())["names"]
occ = {o["code"]: o for o in json.loads((ROOT / "data" / "processed" / "occupations.json").read_text())}
jt = pd.read_excel(ONET / "Job Titles.xlsx", engine="openpyxl")
rep = pd.read_excel(ONET / "Sample of Reported Titles.xlsx", engine="openpyxl")
alts = {}
for c, t in list(zip(jt["O*NET-SOC Code"], jt["Job Title"])) + list(zip(rep["O*NET-SOC Code"], rep["Reported Job Title"])):
    alts.setdefault(c, set()).add(re.sub(r"\s*\(.*\)\s*$", "", str(t)).strip().lower())

toks = lambda s: re.findall(r"[a-z0-9]+(?:-[a-z0-9]+)*", s.lower().replace("--", " "))


def subseq(short, full):
    it = iter(toks(full))
    return all(any(w == x for x in it) for w in toks(short))


def singulars(s):
    w = s.split()
    last = w[-1]
    forms = {last[:-1] if last.endswith("s") else last}
    if last.endswith("ies"):
        forms.add(last[:-3] + "y")
    if last.endswith("es"):
        forms.add(last[:-2])
    if last.endswith("men"):
        forms.add(last[:-3] + "man")
    return {" ".join(w[:-1] + [f]).lower() for f in forms}


errors, rows = [], []
all_names = {o["title"].lower(): c for c, o in occ.items()}
seen = {}
for code, short in names.items():
    o = occ.get(code)
    if not o:
        errors.append(f"{code}: unknown code")
        continue
    if len(short) > 46:
        errors.append(f"{code}: {short!r} is {len(short)} characters")
    if subseq(short, o["title"]):
        src = "official title, shortened"
    elif singulars(short) & alts.get(code, set()):
        src = "O*NET alternate/reported title"
    else:
        src = None
        errors.append(f"{code}: {short!r} is neither a shortening of {o['title']!r} nor an O*NET title")
    k = short.lower()
    if k in seen:
        errors.append(f"{code}: {short!r} also used for {seen[k]}")
    if k in all_names and all_names[k] != code:
        errors.append(f"{code}: {short!r} is the name of another career ({all_names[k]})")
    seen[k] = code
    rows.append((o["title"], short, src))
md = ["# Short career names for page titles", "", "Generated by scripts/etl/verify_short_names.py. The page H1 and text keep the official O*NET name.", "",
      "| Official O*NET title | Short name in the title tag | Source |", "|---|---|---|"]
md += [f"| {a} | {b} | {c} |" for a, b, c in sorted(rows)]
(ROOT / "docs" / "short-names.md").write_text("\n".join(md) + "\n")
print(f"{len(names)} short names checked, {len(errors)} problems")
for e in errors:
    print("  -", e)
sys.exit(1 if errors else 0)
